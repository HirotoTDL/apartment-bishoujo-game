// =====================================================================
//  Character Master Data — 50 Apartment-Themed Bishoujo Characters
// =====================================================================
//  Each character is inspired by a Japanese apartment / residence name.
//  Stats follow rarity-tier baselines; skills unlock by level; evolutions
//  add visual + small stat multiplier at Lv25 and Lv50.
// =====================================================================

import type { Element, SkillId } from "./skills";

export type Rarity = "N" | "R" | "SR" | "SSR" | "UR";

export interface EvolutionStage {
  stage: 1 | 2 | 3;
  unlockLv: number;          // 1, 25, 50
  asset: string;             // base asset id used for image lookup
  statMultiplier: number;    // 1.0 / 1.25 / 1.6
  description: string;       // what changes visually (武装/衣装/etc)
}

export interface BaseStats {
  hp: number;
  atk: number;
  def: number;
  mag: number;
  spd: number;
}

export interface CharacterMaster {
  id: string;
  name: string;
  apartmentSource: string;     // original apartment name (may equal name)
  rarity: Rarity;
  element: Element;
  baseStats: BaseStats;
  growthCurve: "fast" | "normal" | "slow";
  skillLearnset: Array<{ lv: number; skill: SkillId }>;
  evolutions: EvolutionStage[];
  catchRate: number;          // 0..100, base capture rate at 0% HP
  encounterWeight: number;    // higher = appears more often
  lore: string;
  tags: string[];             // for sorting/dex filtering
}

// Stat baseline by rarity (sum total target)
const BASE_TOTAL: Record<Rarity, number> = {
  N: 250, R: 320, SR: 410, SSR: 520, UR: 640,
};

const CATCH_BASE: Record<Rarity, number> = {
  N: 60, R: 35, SR: 15, SSR: 5, UR: 1,
};

const WEIGHT: Record<Rarity, number> = {
  N: 40, R: 30, SR: 10, SSR: 7, UR: 3,
};

// helper to scale base stat percentages to a rarity total
function mkStats(rarity: Rarity, pct: { hp: number; atk: number; def: number; mag: number; spd: number }): BaseStats {
  const sum = pct.hp + pct.atk + pct.def + pct.mag + pct.spd;
  const total = BASE_TOTAL[rarity];
  return {
    hp: Math.round(total * pct.hp / sum * 2.4),  // HP is weighted 2.4x for game balance
    atk: Math.round(total * pct.atk / sum),
    def: Math.round(total * pct.def / sum),
    mag: Math.round(total * pct.mag / sum),
    spd: Math.round(total * pct.spd / sum),
  };
}

function mkEvolutions(idBase: string, descriptions: [string, string, string]): EvolutionStage[] {
  return [
    { stage: 1, unlockLv: 1, asset: `${idBase}_s1`, statMultiplier: 1.0, description: descriptions[0] },
    { stage: 2, unlockLv: 25, asset: `${idBase}_s2`, statMultiplier: 1.25, description: descriptions[1] },
    { stage: 3, unlockLv: 50, asset: `${idBase}_s3`, statMultiplier: 1.6, description: descriptions[2] },
  ];
}

